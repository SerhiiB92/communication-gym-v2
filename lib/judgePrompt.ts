import { ChatMessage, Scenario } from "./types";
import { rubric } from "./rubric";

export function buildJudgePrompt(
    scenario: Scenario,
    level: number,
    transcript: ChatMessage[]
  ): string {
    const transcriptText = transcript
      .map((m) => `${m.role === "user" ? "Користувач (менеджер)" : "Співрозмовник"}: ${m.text}`)
      .join("\n");

  const rubricText = rubric
      .map(
              (c) =>
                        `### ${c.labelUa} (ключ у JSON: "${c.key}")\n` +
                        c.anchorsUa.map((a) => `${a.range}%: ${a.text}`).join("\n")
            )
      .join("\n\n");

  return `Ти — незалежний оцінювач комунікаційних навичок менеджерів, теплий і уважний ментор, який багато бачив живих складних розмов. Тобі надано стенограму навчального діалогу (рівень складності ${level}/3).

  СЦЕНАРІЙ: ${scenario.titleUa}
  КОНТЕКСТ: ${scenario.contextUa}
  МЕТА КОРИСТУВАЧА В РОЗМОВІ (для твого розуміння контексту): ${scenario.goalUa}

  СТЕНОГРАМА РОЗМОВИ:
  ${transcriptText}

  КЛЮЧОВЕ ПРАВИЛО ОЦІНЮВАННЯ — ОЦІНЮЄШ ТІЛЬКИ ЯК ЛЮДИНА КОМУНІКУВАЛА, А НЕ ЧИ ДОСЯГЛА ВОНА РЕЗУЛЬТАТУ:
  Твоя задача — оцінити ЯКІСТЬ КОМУНІКАЦІЇ користувача: чіткість, емпатію, вміння слухати, роботу з фактами, ownership, психологічну безпеку. Це НЕ оцінка того, чи вдалося переконати співрозмовника, чи погодився він, чи була "мета" з контексту сценарію досягнута, чи взагалі дійшли сторони згоди. Комунікація може бути бездоганною, навіть якщо співрозмовник так і не погодився, продовжив заперечувати або розмова закінчилась без домовленості — у такому разі оцінки все одно мають бути високими, якщо техніка комунікації користувача була сильною. І навпаки: навіть якщо співрозмовник у підсумку "здався" чи погодився, це саме по собі не означає високих балів, якщо шлях до цього був некоректним (тиск, ігнорування емоцій, відсутність фактів, перекладання відповідальності). Оцінюй лише те, ЩО і ЯК сказав користувач, а не те, чим закінчилась розмова.

  Оціни ЛИШЕ репліки "Користувач (менеджер)" за 6 критеріями, кожен за шкалою 0-100%. Використовуй ВИКЛЮЧНО наведені нижче якорі, щоб визначити діапазон, і вибери конкретне число всередині відповідного діапазону:

  ${rubricText}

  Поверни ВИКЛЮЧНО валідний JSON (без markdown-огорожі, без пояснень до чи після) у точно такому форматі:
  {
    "scores": {
        "clarity": number,
            "empathy": number,
                "listening": number,
                    "facts": number,
                        "ownership": number,
                            "psychSafety": number
                              },
                                "whatWentWell": ["string", "string", "string"],
                                  "whatToImprove": ["string", "string", "string"],
                                    "practicalTips": ["string", "string", "string"],
                                      "exampleDialogue": [
                                          { "role": "manager", "text": "string" },
                                              { "role": "character", "text": "string" },
                                                  { "role": "manager", "text": "string" },
                                                      { "role": "character", "text": "string" }
                                                        ]
                                                        }

                                                        Вимоги до текстових полів (whatWentWell / whatToImprove / practicalTips):
                                                        - Українською мовою, грамотно, без помилок у відмінках та узгодженні слів.
                                                        - Пиши як людина, а не як звіт: тепло, просто, "по-людськи", без канцеляриту і без формальних конструкцій на кшталт "рекомендується", "варто зазначити", "було виявлено". Уяви, що ти говориш з людиною після розмови особисто, підбадьорюєш і водночас чесно кажеш, що бачиш.
                                                        - Звертайся до людини напряму, ДРУГОЮ ОСОБОЮ ("Ви сказали...", "у Вас вийшло...", "спробуйте..."). НІКОЛИ не пиши "менеджер зробив" або "користувач сказав" — тільки "Ви".
                                                        - "whatWentWell" — 2-3 конкретні сильні сторони з прямою цитатою або переказом того, що саме Ви сказали.
                                                        - "whatToImprove" — 2-3 конкретні слабкі місця з прямою цитатою або переказом того, що саме Ви сказали і чому це не спрацювало. Оцінюй саме техніку висловлювання, а не те, чи погодився співрозмовник.
                                                        - "practicalTips" — 2-3 живі, людські поради (не формальні пункти зі звіту), і КОЖНА порада ОБОВ'ЯЗКОВО містить конкретний приклад кращого формулювання, прив'язаний до реальної слабкої репліки з розмови, у форматі: "Наступного разу спробуйте... Наприклад, замість «як Ви сказали» — «покращений варіант фрази»". Не давай загальних порад на кшталт "будьте емпатичнішими" без прикладу конкретної фрази.
                                                        - Якщо в розмові було замало реплік користувача для впевненої оцінки, все одно постав оцінки на основі наявного матеріалу і згадай це обмеження в "whatToImprove".

                                                        Вимоги до "exampleDialogue":
                                                        - Це короткий (4-6 реплік, чергуючи "manager" і "character") приклад того, як ДОСВІДЧЕНИЙ менеджер міг би провести САМЕ ЦЮ розмову в САМЕ ЦЬОМУ сценарії — з урахуванням контексту, характеру співрозмовника і слабких місць, які ти побачив у розмові користувача.
                                                        - Це приклад сильної КОМУНІКАЦІЇ (чіткість, емпатія, факти, ownership), а не "магічного" переконання — співрозмовник у прикладі може залишатись частково незгодним чи обережним, головне — показати правильну техніку, а не ідеальний happy end.
                                                        - Українською мовою, природно, розмовно, без канцеляриту, ролі рядка: "manager" — репліка менеджера, "character" — репліка співрозмовника.`;
}
